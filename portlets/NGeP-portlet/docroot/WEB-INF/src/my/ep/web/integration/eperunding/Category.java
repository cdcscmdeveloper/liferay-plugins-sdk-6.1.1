package my.ep.web.integration.eperunding;

public class Category {

	private String mainCat;
	private String subCat;
	private String subCatDivision;
	private String status;

	public String getMainCat() {
		return mainCat;
	}

	public void setMainCat(String mainCat) {
		this.mainCat = mainCat;
	}

	public String getSubCat() {
		return subCat;
	}

	public void setSubCat(String subCat) {
		this.subCat = subCat;
	}

	public String getSubCatDivision() {
		return subCatDivision;
	}

	public void setSubCatDivision(String subCatDivision) {
		this.subCatDivision = subCatDivision;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

}
