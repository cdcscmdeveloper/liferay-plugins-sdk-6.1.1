package my.ep.web.integration.crm;

import java.util.Date;

public class Appl {

	private String applNo;
	private String applStatus;
	private String appType;
	private String mofNo;
	private Date expiryDate;
	private String regNo;
	private int accountStatus;
	private String capitalPaidUp;

	public String getApplNo() {
		return applNo;
	}

	public void setApplNo(String applNo) {
		this.applNo = applNo;
	}

	public String getApplStatus() {
		return applStatus;
	}

	public void setApplStatus(String applStatus) {
		this.applStatus = applStatus;
	}

	public String getAppType() {
		return appType;
	}

	public void setAppType(String appType) {
		this.appType = appType;
	}

	public String getMofNo() {
		return mofNo;
	}

	public void setMofNo(String mofNo) {
		this.mofNo = mofNo;
	}

	public Date getExpiryDate() {
		return expiryDate;
	}

	public void setExpiryDate(Date expiryDate) {
		this.expiryDate = expiryDate;
	}

	public String getRegNo() {
		return regNo;
	}

	public void setRegNo(String regNo) {
		this.regNo = regNo;
	}

	public int getAccountStatus() {
		return accountStatus;
	}

	public void setAccountStatus(int accountStatus) {
		this.accountStatus = accountStatus;
	}

	public String getCapitalPaidUp() {
		return capitalPaidUp;
	}

	public void setCapitalPaidUp(String capitalPaidUp) {
		this.capitalPaidUp = capitalPaidUp;
	}

}
